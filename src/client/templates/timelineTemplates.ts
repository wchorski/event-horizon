import type { InsertableTimelineGraph, TimelineState } from "@ty/Schema";

const now = new Date();

export const buildFromTemplate = (
  base: TimelineState,
  timelineUuid: string,
) => {

  return {
    ...base,
    id: timelineUuid,

    groups: base.groups.map((g) => ({
      ...g,
      timelineUuid,
      sourceId: g.id,
      id: undefined, // let IDB generate
    })),

    skills: base.skills.map((s) => ({
      ...s,
      timelineUuid,
      sourceId: s.id,
      id: undefined,
    })),

    moments: base.moments.map((m) => ({
      ...m,
      timelineUuid,
      sourceId: m.id,
      sourceGroupId: m.groupId,
      sourceSkillId: m.skillId,
      id: undefined,
    })),

    steps: base.steps.map((s) => ({
      ...s,
      timelineUuid,
      sourceId: s.id,
      source_moment_id: s.momentId,
      id: undefined,
    })),
  };
};
export function buildInsertableTimelineGraph(
  base: TimelineState,
  timelineUuid: string,
  bookingUuid: string | null,
): InsertableTimelineGraph {
  return {
    ...base,
    id: timelineUuid,
    bookingUuid,

    groups: base.groups.map(({ id, ...g }) => ({
      ...g,
      timelineUuid,
      sourceId: id,
    })),

    skills: base.skills.map(({ id, ...s }) => ({
      ...s,
      timelineUuid,
      sourceId: id,
    })),

    moments: base.moments.map(({ id, groupId, skillId, ...m }) => ({
      ...m,
      timelineUuid,
      sourceId: id,
      sourceGroupId: groupId,
      sourceSkillId: skillId,
    })),

    steps: base.steps.map(({ id, momentId, ...s }) => ({
      ...s,
      timelineUuid,
      sourceId: id,
      sourceMomentId: momentId,
    })),
  };
}

